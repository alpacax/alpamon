// with returns a copy of files with the given paths added or replaced.
func with(files map[string]string, changes map[string]string) map[string]string {
	out := maps.Clone(files)
	maps.Copy(out, changes)
	return out
}

func without(files map[string]string, paths ...string) map[string]string {
	out := with(files, nil)
	for _, p := range paths {
		delete(out, p)
	}
	return out
}

func buildLoginCaptureRoot(t *testing.T, files map[string]string, bins []string) string {
	t.Helper()
	root := t.TempDir()
	for p, content := range files {
		full := filepath.Join(root, p)
		require.NoError(t, os.MkdirAll(filepath.Dir(full), 0o755))
		require.NoError(t, os.WriteFile(full, []byte(content), 0o644))
	}
	for _, b := range bins {
		full := filepath.Join(root, b)
		require.NoError(t, os.MkdirAll(filepath.Dir(full), 0o755))
		require.NoError(t, os.WriteFile(full, []byte("#!/bin/false\n"), 0o755))
	}
	return root
}

// fakeSSHD stands in for `sshd -T` and counts its runs.
type fakeSSHD struct {
	out   string
	err   error
	runs  int
	panic bool
}

func (f *fakeSSHD) run(_ context.Context, _ string) ([]byte, error) {
	f.runs++
	if f.panic {
		panic("sshd runner exploded")
	}
	return []byte(f.out), f.err
}

// countingReader wraps os.ReadFile, counts reads and can fail chosen paths.
type countingReader struct {
	reads int
	fail  map[string]error
}

func (r *countingReader) read(path string) ([]byte, error) {
	r.reads++
	for suffix, err := range r.fail {
		if strings.HasSuffix(path, suffix) {
			return nil, err
		}
	}
	return os.ReadFile(path)
}

func newTestCollector(root string, sshd *fakeSSHD, reader *countingReader) *loginCaptureCollector {
	c := newLoginCaptureCollector(root)
	c.runSSHDT = sshd.run
	if reader != nil {
		c.readFile = reader.read
	}
	return c
}

