// TestLoginCapturePanicIsContained checks that a failure inside the
// collector yields no block instead of reaching the report, and that the
// collector works again afterwards.
func TestLoginCapturePanicIsContained(t *testing.T) {
	root := buildLoginCaptureRoot(t, debianFiles(), debianBins)

	sshd := &fakeSSHD{out: "usepam yes\n", panic: true}
	c := newTestCollector(root, sshd, nil)
	var got *LoginCapture
	assert.NotPanics(t, func() { got = c.Get() })
	assert.Nil(t, got)

	c = newTestCollector(root, &fakeSSHD{out: "usepam yes\n"}, nil)
	c.readFile = func(string) ([]byte, error) { panic("read exploded") }
	assert.NotPanics(t, func() { got = c.Get() })
	assert.Nil(t, got)

	c.readFile = os.ReadFile
	got = c.Get()
	require.NotNil(t, got, "a contained failure must not wedge the collector")
	assert.Equal(t, HookRegistered, got.Hooks.SSHD)
}
